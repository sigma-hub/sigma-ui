import MarkdownIt from 'markdown-it';
import type { ApiTableItems, ApiTableKind, ComponentApi } from '../../.vitepress/theme/types/api';

const markdown = new MarkdownIt();

const TABLE_KINDS: ApiTableKind[] = ['props', 'events', 'slots', 'methods'];

export const GENERATED_HEADER = '<!-- Generated by `pnpm docs:gen` from packages/lib. Do not edit manually. -->';

function renderDescription(description: string) {
  return description ? markdown.render(description).trim() : '';
}

function escapeAttribute(value: string) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('\'', '&#39;');
}

function renderTable<Kind extends ApiTableKind>(kind: Kind, items: ApiTableItems[Kind]) {
  const renderedItems = items.map(item => ({ ...item, description: renderDescription(item.description) }));
  return `<ApiTable kind="${kind}" :items='${escapeAttribute(JSON.stringify(renderedItems, null, 2))}' />`;
}

export function renderComponentApi(api: ComponentApi) {
  const sections = api.parts.map((part) => {
    const tables = TABLE_KINDS
      .filter(kind => part[kind].length)
      .map(kind => renderTable(kind, part[kind]));

    const body = tables.length ? tables.join('\n\n') : 'This component has no props, events, or slots.';
    return `### ${part.name}\n\n${body}`;
  });

  return `${GENERATED_HEADER}\n\n${sections.join('\n\n')}\n`;
}
