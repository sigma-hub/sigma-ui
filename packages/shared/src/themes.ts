export function toRegistryTheme(theme: Theme) {
  return {
    name: theme.name,
    type: 'registry:theme' as const,
    title: theme.label,
    cssVars: {
      light: Object.fromEntries(themeColorKeys.map(key => [key, theme.cssVars.light[key]])),
      dark: Object.fromEntries(themeColorKeys.map(key => [key, theme.cssVars.dark[key]])),
    },
  };
}
